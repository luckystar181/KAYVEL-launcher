import assert from 'node:assert/strict';
import { mkdtemp, readFile, readdir, stat } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';
import { runInNewContext } from 'node:vm';
import ts from 'typescript';

if (process.platform !== 'win32' || process.arch !== 'x64') throw new Error('Windows x64 required.');
const [directory, ...extra] = process.argv.slice(2);
if (!directory || extra.length) throw new Error('Usage: node scripts/check-bundled-java.mjs EXTRACTED_RESOURCES_APP');
const app = resolve(directory);
const load = name => import(pathToFileURL(join(app, 'dist', 'main', name)).href);
const bundle = await load('bundled-java.js');
const java = await load('java-runtime.js');
const install = await load('install-files.js');
const session = await load('download-session.js');
const { PreparationFiles } = await load('preparation-files.js');
const progress = await load('preparation-progress.js');
const source = await readFile(join(app, 'dist/main/prepare-java.js'), 'utf8');
const { outputText } = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } });
const require = createRequire(import.meta.url);
const exports = {};
globalThis.fetch = () => { throw new Error('Network forbidden in bundled Java smoke'); };
runInNewContext(outputText, { exports, Buffer, Error, process: { platform: 'win32', arch: 'x64' }, require(name) {
  if (name === './java-runtime.js') return { ...java, availableJava21: () => null };
  if (name === './bundled-java.js') return bundle;
  if (name === './install-files.js') return install;
  if (name === './download-session.js') return session;
  if (name === './preparation-progress.js') return progress;
  return require(name);
} });
const root = await mkdtemp(join(process.env.LOCALAPPDATA, 'Temp/opencode/kayvel-bundled-java-'));
const files = new PreparationFiles(root);
files.downloads = () => { throw new Error('Downloads forbidden'); };
const controller = new AbortController();
controller.abort(new Error('smoke cancellation'));
await assert.rejects(session.withDownloadSignal(controller.signal, () => exports.prepareJava(files, root, () => {})), /smoke cancellation/);
assert.deepEqual(await readdir(root), []);
const executable = await exports.prepareJava(files, root, () => {});
assert.equal(executable, join(root, exports.PREPARED_JAVA));
assert.ok((await stat(executable)).isFile());
assert.ok(files.receipts.has(`runtime/${bundle.BUNDLED_JAVA_ROOT}/notice`.toLowerCase()));
assert.ok(files.receipts.has(`runtime/${bundle.BUNDLED_JAVA_ROOT}/legal/java.base/license`.toLowerCase()));
assert.equal(files.receipts.get('.preparation/java.zip').sha256, bundle.BUNDLED_JAVA_SHA256);
console.log(`PASS: actual packaged Java bundle verified, ${files.receipts.size} receipts, local extraction and Java -version validation; pre-cancellation wrote no files. Network disabled. No Minecraft, launcher or working profile used.\nIsolated runtime: ${root}`);
